export const plannerEn = Object.fromEntries(Object.keys(plannerCs).map(key => [key, key]));
export function plannerTranslator(locale = "en") {
    return (key, parameters = {}) => (locale === "cs" ? plannerCs[key] : plannerEn[key]).replace(/\{(\w+)\}/gu, (token, name) => Object.hasOwn(parameters, name) ? String(parameters[name] ?? "") : token);
}
/** A package-owned failure retains its message until the receiving view chooses its locale. */
export class PlannerError extends Error {
    render;
    constructor(key, parameters = {}) {
        const render = typeof key === "function" ? key : (t) => t(key, parameters);
        super(render(plannerTranslator()));
        this.render = render;
    }
}
export function plannerError(error, t, fallback) {
    return error instanceof PlannerError ? error.render(t) : fallback;
}
/** Code-owned enum labels only; authored titles and descriptions bypass this lookup. */
export function plannerLabel(value, t) {
    return Object.hasOwn(plannerCs, value) ? t(value) : value;
}
